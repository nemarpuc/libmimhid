class GenerateError(Exception):
    pass


# ---- Types ------------------------------------------------------------------------------


@dataclass(frozen=True)
class T:
    """A parsed C type: kind is base, ptr or array."""

    kind: str
    name: str = ""            # base
    inner: Any = None         # ptr, array: the T pointed to or held
    const: bool = False       # ptr: the pointee is const
    count: int = 0            # array


def parse_type(text: str) -> T:
    q = text.strip()
    if q.endswith("*const"):  # a const pointer value; the qualifier does not change the layout
        q = q[:-5].strip()
    m = re.match(r"^(.*?)\s*\[(\d+)\]$", q)
    if m:
        return T("array", inner=parse_type(m.group(1)), count=int(m.group(2)))
    if q.endswith("*"):
        inner = q[:-1].strip()
        const = False
        if inner.endswith(" const"):
            inner = inner[:-6].strip()
            const = True
        elif inner.startswith("const "):
            const = True
        return T("ptr", inner=parse_type(inner), const=const)
    q = re.sub(r"^(const|volatile)\s+", "", q)
    q = re.sub(r"^struct\s+", "", q)
    return T("base", name=q)


@dataclass
class Field:
    name: str
    type: T


@dataclass
class Struct:
    name: str
    fields: list[Field]


@dataclass
class Func:
    name: str
    ret: T
    params: list[Field]


@dataclass
class FuncPtr:
    name: str
    ret: T
    params: list[T]


@dataclass
class EnumType:
    name: str
    members: list[tuple[str, int]]


@dataclass
class Model:
    order: list[tuple[str, object]] = field(default_factory=list)  # (kind, object) in header order
    handles: list[str] = field(default_factory=list)
    structs: dict[str, Struct] = field(default_factory=dict)
    funcptrs: dict[str, FuncPtr] = field(default_factory=dict)
    enums: dict[str, EnumType] = field(default_factory=dict)
    flags: list[tuple[str, int]] = field(default_factory=list)  # enumerators with no type name
    macros: list[tuple[str, int, bool]] = field(default_factory=list)  # name, value, unsigned
    baud_rates: list[int] = field(default_factory=list)
    funcs: list[Func] = field(default_factory=list)


# ---- Reading the header -----------------------------------------------------------------


def clang() -> str:
    return os.environ.get("CLANG", "clang")  # for example CLANG=clang-14 on a CI runner


def run(command: list[str]) -> str:
    try:
        return subprocess.run(command, check=True, capture_output=True, text=True, cwd=ROOT).stdout
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", "") or str(error)
        raise GenerateError(f"{' '.join(command)} failed: {detail.strip()}") from error


def load_model() -> Model:
    ast = json.loads(
        run([clang(), "-std=c11", "-Xclang", "-ast-dump=json", "-fsyntax-only", "-Iinclude",
             HEADER_NAME])
    )
    nodes = ast["inner"]
    model = Model()
    complete: dict[str, Struct] = {}
    forward: list[str] = []

    for node in nodes:
        kind = node["kind"]
        name = node.get("name", "")
        if kind == "RecordDecl" and name.startswith(PREFIX):
            if node.get("completeDefinition"):
                fields = [Field(f["name"], parse_type(f["type"]["qualType"]))
                          for f in node.get("inner", []) if f["kind"] == "FieldDecl"]
                complete[name] = Struct(name, fields)
                model.structs[name] = complete[name]
                model.order.append(("struct", complete[name]))
            elif name not in forward:
                forward.append(name)
        elif kind == "TypedefDecl" and name.startswith(PREFIX):
            qual = node["type"]["qualType"]
            if "(*)" in qual:
                m = re.match(r"^(.*?)\s*\(\*\)\((.*)\)$", qual)
                if m is None:
                    raise GenerateError(f"cannot read the function pointer type {qual!r}")
                params = [parse_type(p) for p in re.split(r",\s*", m.group(2)) if p != "void"]
                funcptr = FuncPtr(name, parse_type(m.group(1)), params)
                model.funcptrs[name] = funcptr
                model.order.append(("funcptr", funcptr))
            elif qual == "int32_t":
                model.enums[name] = EnumType(name, [])
                model.order.append(("enum", model.enums[name]))
        elif kind == "FunctionDecl" and name.startswith(PREFIX):
            if node.get("storageClass") == "static" or node.get("inline"):
                continue
            fn_type = parse_type(node["type"]["qualType"].split("(")[0])
            params = [Field(p.get("name") or f"arg{i}", parse_type(p["type"]["qualType"]))
                      for i, p in enumerate(q for q in node.get("inner", [])
                                            if q["kind"] == "ParmVarDecl")]
            model.funcs.append(Func(name, fn_type, params))

    model.handles = [n for n in forward if n not in complete]
    for handle in model.handles:
        model.order.insert(0, ("handle", handle))

    # An enumeration is the anonymous enum that follows its int32_t typedef.
    previous_enum: EnumType | None = None
    for node in nodes:
        if node["kind"] == "TypedefDecl" and node.get("name") in model.enums:
            previous_enum = model.enums[node["name"]]
            continue
        if node["kind"] == "EnumDecl" and not node.get("name"):
            members: list[tuple[str, int]] = []
            value = -1
            for constant in node.get("inner", []):
                if constant["kind"] != "EnumConstantDecl":
                    continue
                explicit = [i for i in constant.get("inner", []) if i["kind"] == "ConstantExpr"]
                value = int(explicit[0]["value"]) if explicit else value + 1
                members.append((constant["name"], value))
            if previous_enum is not None and not previous_enum.members:
                previous_enum.members = members
            else:
                model.flags.extend(members)
        previous_enum = None

    defines = run([clang(), "-E", "-dM", "-std=c11", "-Iinclude", HEADER_NAME])
    for line in sorted(defines.splitlines()):
        m = re.match(rf"^#define ({UPPER}[A-Z0-9_]+) ([0-9]+)([uU]?)$", line)
        if m:
            model.macros.append((m.group(1), int(m.group(2)), bool(m.group(3))))
        m = re.match(rf"^#define {UPPER}BAUD_RATES \{{ (.*) \}}$", line)
        if m:
            model.baud_rates = [int(x.rstrip("uU")) for x in m.group(1).split(",")]
    if NAME == "mimhid" and not model.baud_rates:
        raise GenerateError("MIMHID_BAUD_RATES not found")  # only the serial library has a line rate
    model.macros.sort(key=lambda item: item[0])
    return model


# ---- Names ------------------------------------------------------------------------------


def pascal(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in text.split("_") if part)


# Short names that differ from the C name with its prefix cut. libaoahid's bindings used these
# before they were generated, and a binding's names are public API.
TYPE_RENAMES = {f"{PREFIX}report_id_option": "ReportId",
                f"{PREFIX}interface_claim_policy": "ClaimPolicy"}


def type_name(c_name: str) -> str:
    return TYPE_RENAMES.get(c_name) or pascal(c_name[len(PREFIX):])


def all_constants(model: Model) -> list[tuple[str, int, str]]:
    """(name, value, kind) with kind 'enum' (int32) or 'u32'/'i32' for macros."""
    out: list[tuple[str, int, str]] = []
    for name, value, unsigned in model.macros:
        version = name in (f"{UPPER}VERSION_{part}" for part in ("MAJOR", "MINOR", "PATCH"))
        out.append((name, value, "u32" if unsigned or version or value > 0x7FFFFFFF else "i32"))
    for enum in model.enums.values():
        out.extend((n, v, "enum") for n, v in enum.members)
    out.extend((n, v, "enum") for n, v in model.flags)
    return out


def check_names(model: Model) -> None:
    seen: dict[str, str] = {}
    for name in list(model.handles) + list(model.structs) + list(model.funcptrs) + list(model.enums):
        short = type_name(name)
        if short in seen:
            raise GenerateError(f"{name} and {seen[short]} both become {short}")
        seen[short] = name
    for struct in model.structs.values():
        for f in struct.fields:
            if pascal(f.name) == type_name(struct.name):
                raise GenerateError(f"{struct.name}.{f.name} would share its C# type's name")
            if keyword.iskeyword(f.name):
                raise GenerateError(f"{struct.name}.{f.name} is a Python keyword")
    for func in model.funcs:
        for p in func.params:
            if keyword.iskeyword(p.name):
                raise GenerateError(f"{func.name}({p.name}) is a Python keyword")


def kind_of(model: Model, name: str) -> str:
    if name in model.enums:
        return "enum"
    if name in model.structs:
        return "struct"
    if name in model.handles:
        return "handle"
    if name in model.funcptrs:
        return "funcptr"
    if name in BASE:
        return "int"
    if name == "void":
        return "void"
    raise GenerateError(f"unknown C type {name!r}")


# ---- Python -----------------------------------------------------------------------------


def py_type(model: Model, t: T) -> str:
    if t.kind == "array":
        return f"{py_type(model, t.inner)} * {t.count}"
    if t.kind == "ptr":
        inner = t.inner
        if inner.kind == "base":
            k = kind_of(model, inner.name)
            if inner.name == "char":
                return "c.c_char_p"
            if k == "void":
                return "c.c_void_p"
            if k == "handle":
                return f"{type_name(inner.name)}P"
            return f"c.POINTER({py_type(model, inner)})"
        if inner.kind == "ptr" and inner.inner.kind == "base" and inner.inner.name == "char":
            return "c.POINTER(c.c_char_p)"
        return f"c.POINTER({py_type(model, inner)})"
    k = kind_of(model, t.name)
    if k == "enum":
        return "c.c_int32"
    if k in ("struct", "funcptr"):
        return type_name(t.name)
    if k == "int":
        return BASE[t.name][0]
    raise GenerateError(f"cannot pass {t.name} by value")


def py_return(model: Model, t: T) -> str:
    if t.kind == "base" and t.name == "void":
        return "None"
    return py_type(model, t)


def gen_python(model: Model) -> str:
    out = [
        f"# {BANNER}",
        f"# {COPYRIGHT}",
        f"# {GENERATED}",
        '"""Complete, literal ctypes declarations for the stable ``mimhid.h`` C ABI.',
        "",
        "The binding chooses no option overrides: the caller fills ``struct_size`` and every",
        "field. The static inline initializers of ``mimhid.h`` are C code and are not bound.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import ctypes as c",
        "import os",
        "from typing import Union",
        "",
    ]
    for name, value, _ in all_constants(model):
        out.append(f"{name} = {value}")
    if model.baud_rates:
        out.append("MIMHID_BAUD_RATES = (" + ", ".join(str(r) for r in model.baud_rates) + ")")
    out.append("")
    for kind, obj in model.order:
        if kind == "handle":
            out += ["", f"class {type_name(obj)}(c.Structure):", "    pass", "",
                    f"{type_name(obj)}P = c.POINTER({type_name(obj)})"]
        elif kind == "funcptr":
            args = ", ".join(py_type(model, p) for p in obj.params)
            ret = py_return(model, obj.ret)
            out += ["", f"{type_name(obj.name)} = c.CFUNCTYPE({ret}, {args})"]
        elif kind == "struct":
            out += ["", "", f"class {type_name(obj.name)}(c.Structure):", "    _fields_ = ["]
            for f in obj.fields:
                out.append(f'        ("{f.name}", {py_type(model, f.type)}),')
            out.append("    ]")
    out += ["", "", "ABI_STRUCTS = {"]
    for struct in model.structs.values():
        out.append(f'    "{struct.name}": {type_name(struct.name)},')
    out += ["}", "", "",
            "def load(path: Union[os.PathLike, str]) -> c.CDLL:",
            '    """Load exactly the caller-selected shared library and declare every symbol."""',
            "    library = c.CDLL(os.fspath(path))", "",
            "    def declare(name: str, arguments: list[object], result: object) -> None:",
            "        function = getattr(library, name)",
            "        function.argtypes = arguments",
            "        function.restype = result", ""]
    for func in model.funcs:
        args = ", ".join(py_type(model, p.type) for p in func.params)
        out.append(f'    declare("{func.name}", [{args}], {py_return(model, func.ret)})')
    out += ["    return library", "", "",
            "# Keep ``from mimhid import *`` to the stable binding surface.",
            '__all__ = [name for name in globals() if name.startswith("MIMHID_")]',
            "__all__ += ["]
    for kind, obj in model.order:
        if kind == "enum":
            continue  # an enumeration is int32_t plus its MIMHID_ constants
        if kind == "handle":
            out.append(f'    "{type_name(obj)}",')
            out.append(f'    "{type_name(obj)}P",')
        else:
            out.append(f'    "{type_name(obj.name)}",')
    out += ['    "ABI_STRUCTS",', '    "load",', "]", ""]
    return "\n".join(out)


def gen_python_test(model: Model) -> str:
    out = [
        "#!/usr/bin/env python3",
        f"# {BANNER}",
        f"# {COPYRIGHT}",
        f"# {GENERATED}",
        '"""Compare the ctypes layout with the sizes and offsets the C compiler produced.',
        "",
        "MIMHID_ABI_ORACLE names the built layout_oracle program.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import os",
        "import subprocess",
        "import sys",
        "",
        "import mimhid.native as native",
        "",
        "",
        "def oracle() -> dict[str, int]:",
        '    path = os.environ.get("MIMHID_ABI_ORACLE")',
        "    if not path:",
        '        raise SystemExit("MIMHID_ABI_ORACLE is not set")',
        "    text = subprocess.run([path], check=True, capture_output=True, text=True).stdout",
        '    return {k: int(v) for k, v in (line.split("=", 1) for line in text.splitlines())}',
        "",
        "",
        "LAYOUT = {",
    ]
    for struct in model.structs.values():
        fields = ", ".join(f'"{f.name}"' for f in struct.fields)
        out.append(f'    "{struct.name}": ("{type_name(struct.name)}", [{fields}]),')
    out += ["}", "", "CONSTANTS = ["]
    out += [f'    "{n}",' for n, _, _ in all_constants(model)]
    out += [
        "]", "", "",
        "def main() -> int:",
        "    expected = oracle()",
        "    failures: list[str] = []",
        "    for c_name, (cls_name, fields) in LAYOUT.items():",
        "        cls = getattr(native, cls_name)",
        '        if "struct_size" in fields and cls().struct_size != 0:',
        '            failures.append(f"{c_name}: the binding fills struct_size")',
        "        if native.ABI_STRUCTS.get(c_name) is not cls:",
        '            failures.append(f"{c_name}: missing from ABI_STRUCTS")',
        '        if native.c.sizeof(cls) != expected[f"{c_name}.size"]:',
        '            failures.append(f"{c_name}.size")',
        "        for name in fields:",
        '            if getattr(cls, name).offset != expected[f"{c_name}.{name}"]:',
        '                failures.append(f"{c_name}.{name}")',
        "    for name in CONSTANTS:",
        "        if getattr(native, name) != expected[name]:",
        '            failures.append(f"{name}")',
        "    if set(native.ABI_STRUCTS) != set(LAYOUT):",
        '        failures.append("ABI_STRUCTS differs from the header")',
        "    for failure in failures:",
        '        print("layout mismatch:", failure, file=sys.stderr)',
        "    return 1 if failures else 0",
        "", "",
        'if __name__ == "__main__":',
        "    raise SystemExit(main())", ""]
    return "\n".join(out)


# ---- C oracle ---------------------------------------------------------------------------


def gen_oracle(model: Model) -> str:
    out = [
        f"// {BANNER}",
        f"// {COPYRIGHT}",
        f"// {GENERATED}",
        "/* Emits compiler-observed C ABI sizes, offsets and constants for the foreign-binding",
        " * tests; it does not validate protocol behavior. */",
        '#include "mimhid.h"',
        "",
        "#include <stddef.h>",
        "#include <stdio.h>",
        "",
        '#define CONSTANT(name) printf(#name "=%lld\\n", (long long)(name))',
        '#define SIZE(type) printf(#type ".size=%zu\\n", sizeof(type))',
        '#define OFFSET(type, field) printf(#type "." #field "=%zu\\n", offsetof(type, field))',
        "",
        "int main(void) {",
    ]
    for name, _, _ in all_constants(model):
        out.append(f"    CONSTANT({name});")
    for struct in model.structs.values():
        out.append(f"    SIZE({struct.name});")
        for f in struct.fields:
            out.append(f"    OFFSET({struct.name}, {f.name});")
    out += ["    return 0;", "}", ""]
    return "\n".join(out)


