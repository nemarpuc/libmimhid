# The one spelling that is not the C name with its prefix cut: libaoahid's C# says Result.Parameter.
CS_MEMBER_RENAMES = {(f"{PREFIX}result", "Param"): "Parameter"}


def cs_enum_members(enum: EnumType) -> list[tuple[str, int]]:
    names = [n[len(UPPER):] for n, _ in enum.members]
    prefix = ""
    if len(names) > 1:
        parts = [n.split("_") for n in names]
        shared = []
        for column in zip(*parts):
            if len(set(column)) != 1:
                break
            shared.append(column[0])
        # Never strip a whole name away.
        while shared and any(len(p) <= len(shared) for p in parts):
            shared.pop()
        prefix = "_".join(shared) + "_" if shared else ""
    members = []
    for (full, value), short in zip(enum.members, names):
        member = pascal(short[len(prefix):].lower())
        if enum.name.endswith("_result") and member.startswith("Err"):
            member = member[3:]  # Result.Parameter, as in libaoahid, not Result.ErrParameter
        member = CS_MEMBER_RENAMES.get((enum.name, member), member)
        if member[:1].isdigit():
            member = "N" + member
        members.append((member, value))
    return members


def cs_scalar(model: Model, t: T) -> str:
    k = kind_of(model, t.name)
    if k == "enum":
        return type_name(t.name)
    if k == "struct":
        return type_name(t.name)
    if k == "int":
        return BASE[t.name][1]
    raise GenerateError(f"cannot pass {t.name} by value")


CS_FIXED_ELEMENTS = {"byte", "ushort", "uint", "ulong", "int", "short", "sbyte", "long"}


def has_fixed_buffer(obj: Struct) -> bool:
    return any(f.type.kind == "array" for f in obj.fields)


def cs_field(model: Model, f: Field) -> list[str]:
    t = f.type
    name = pascal(f.name)
    if t.kind == "array":
        element = cs_scalar(model, t.inner)
        if element not in CS_FIXED_ELEMENTS:
            raise GenerateError(f"{f.name}: C# cannot hold {element} in a fixed buffer")
        # A fixed buffer keeps the structure blittable: no marshalling copy, and a default
        # structure (all zero) is valid without allocating an array first.
        return [f"    public fixed {element} {name}[{t.count}];"]
    if t.kind == "ptr":
        return [f"    public nint {name};"]
    if t.kind == "base" and kind_of(model, t.name) == "funcptr":
        return [f"    public nint {name};"]
    return [f"    public {cs_scalar(model, t)} {name};"]


def camel(text: str) -> str:
    head, *rest = text.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


# size_t* parameters whose C name does not say "out_" but whose contract is an output only: the
# function stores the length of the bytes it returns and reads nothing.
OUTPUT_ONLY = {(f"{PREFIX}spec_descriptor", "length")}


def cs_param(model: Model, func: Func, p: Field, raw: bool, taken: set[str]) -> str:
    t = p.type
    # An output parameter is named for what it returns (out nint node, not out nint outNode),
    # unless an input already has that name.
    short = p.name[4:] if p.name.startswith("out_") and p.name[4:] not in taken else p.name
    name = camel(short)
    if name in CSHARP_KEYWORDS:
        name = "@" + name
    if t.kind == "ptr":
        inner = t.inner
        if inner.kind == "ptr":
            return f"out nint {name}"
        if inner.kind == "base" and kind_of(model, inner.name) == "struct" and not raw:
            return f"{'in' if t.const else 'ref'} {type_name(inner.name)} {name}"
        if inner.kind == "base" and inner.name == "size_t" and not t.const:
            # Only the C name says an output ("out_"); any other size_t* may carry a value in.
            output = p.name.startswith("out_") or (func.name, p.name) in OUTPUT_ONLY
            return f"{'out' if output else 'ref'} nuint {name}"
        return f"nint {name}"
    return f"{cs_scalar(model, t)} {name}"


def cs_return(model: Model, t: T) -> str:
    if t.kind == "ptr":
        return "nint"
    if t.kind == "base" and t.name == "void":
        return "void"
    return cs_scalar(model, t)


def has_struct_pointer(model: Model, func: Func) -> bool:
    return any(p.type.kind == "ptr" and p.type.inner.kind == "base"
               and kind_of(model, p.type.inner.name) == "struct" for p in func.params)


def gen_csharp(model: Model) -> str:
    out = [
        f"// {BANNER}",
        f"// {COPYRIGHT}",
        f"// {GENERATED}",
        "// Mirrors the stable native ABI without option initializers or native library",
        "// deployment policy.",
        "using System.Runtime.InteropServices;",
        "",
        "namespace MimHid;",
        "",
    ]
    for enum in model.enums.values():
        members = cs_enum_members(enum)
        one_line = (f"public enum {type_name(enum.name)} : int {{ "
                    + ", ".join(f"{m} = {v}" for m, v in members) + " }")
        if len(one_line) <= 100:
            out += [one_line, ""]
            continue
        out += [f"public enum {type_name(enum.name)} : int", "{"]
        out += [f"    {member} = {value}," for member, value in members]
        out += ["}", ""]
    for kind, obj in model.order:
        if kind == "struct":
            unsafe = "unsafe " if has_fixed_buffer(obj) else ""
            out += ["[StructLayout(LayoutKind.Sequential)]",
                    f"public {unsafe}struct {type_name(obj.name)}", "{"]
            for f in obj.fields:
                out += cs_field(model, f)
            out += ["}", ""]
    out += ["public static class Native", "{",
            '    private const string Library = "mimhid";',
            "    private const CallingConvention Call = CallingConvention.Cdecl;", ""]
    for name, value, kind in all_constants(model):
        cs_kind = {"u32": "uint", "i32": "int", "enum": "int"}[kind]
        out.append(f"    public const {cs_kind} {name} = {value};")
    if model.baud_rates:
        out.append("    public static readonly uint[] MIMHID_BAUD_RATES = { "
                   + ", ".join(f"{r}u" for r in model.baud_rates) + " };")
    out.append("")
    out.append("    public static readonly IReadOnlyDictionary<string, Type> AbiStructs =")
    out.append("        new Dictionary<string, Type>")
    out.append("        {")
    for struct in model.structs.values():
        out.append(f'            ["{struct.name}"] = typeof({type_name(struct.name)}),')
    out += ["        };", ""]
    out.append("    public static readonly IReadOnlyDictionary<string, long> AbiConstants =")
    out.append("        new Dictionary<string, long>")
    out.append("        {")
    for name, value, _ in all_constants(model):
        out.append(f'            ["{name}"] = {value},')
    out += ["        };", ""]
    for func in model.funcs:
        short = type_name(func.name)
        variants = [False]
        if has_struct_pointer(model, func):
            variants.append(True)  # the same entry point with every struct pointer as nint
        for raw in variants:
            taken = {q.name for q in func.params}
            params = ", ".join(cs_param(model, func, p, raw, taken) for p in func.params)
            out.append(f'    [DllImport(Library, EntryPoint = "{func.name}", ExactSpelling = true, '
                       "CallingConvention = Call)]")
            out.append(f"    public static extern {cs_return(model, func.ret)} {short}({params});")
    out += ["}", ""]
    return "\n".join(out)


