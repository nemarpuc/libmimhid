def rs_ident(name: str) -> str:
    return f"r#{name}" if name in RUST_KEYWORDS else name


def rs_type(model: Model, t: T) -> str:
    if t.kind == "array":
        return f"[{rs_type(model, t.inner)}; {t.count}]"
    if t.kind == "ptr":
        mut = "const" if t.const else "mut"
        inner = t.inner
        if inner.kind == "base" and inner.name == "void":
            return f"*{mut} c_void"
        return f"*{mut} {rs_type(model, inner)}"
    k = kind_of(model, t.name)
    if k == "int":
        return BASE[t.name][2]
    if k in ("enum", "struct", "handle", "funcptr"):
        return t.name
    raise GenerateError(f"cannot pass {t.name} by value")


def rs_return(model: Model, t: T) -> str:
    if t.kind == "base" and t.name == "void":
        return ""
    return f" -> {rs_type(model, t)}"


def gen_rust(model: Model) -> str:
    out = [
        f"// {BANNER}",
        f"// {COPYRIGHT}",
        f"// {GENERATED}",
        "//! Mirrors the stable C ABI literally; policy and ownership live elsewhere.",
        "",
        "#![allow(non_camel_case_types)]",
        "",
        "use core::ffi::{c_char, c_void};",
        "",
        "macro_rules! opaque {",
        "    ($($name:ident),+ $(,)?) => {$(",
        "        #[repr(C)]",
        "        pub struct $name { _private: [u8; 0] }",
        "    )+};",
        "}",
        "opaque!(" + ", ".join(model.handles) + ");",
        "",
    ]
    for enum in model.enums.values():
        out.append(f"pub type {enum.name} = i32;")
    out.append("")
    for name, value, kind in all_constants(model):
        rs_kind = {"u32": "u32", "i32": "i32", "enum": "i32"}[kind]
        out.append(f"pub const {name}: {rs_kind} = {value};")
    if model.baud_rates:
        out.append(f"pub const MIMHID_BAUD_RATES: [u32; {len(model.baud_rates)}] = ["
                   + ", ".join(str(r) for r in model.baud_rates) + "];")
    out.append("")
    for kind, obj in model.order:
        if kind == "funcptr":
            params = ", ".join(f"{chr(97 + i)}: {rs_type(model, p)}"
                               for i, p in enumerate(obj.params))
            out.append(f"pub type {obj.name} = Option<unsafe extern \"C\" fn({params})"
                       f"{rs_return(model, obj.ret)}>;")
        elif kind == "struct":
            out += ["", "#[repr(C)]", f"pub struct {obj.name} {{"]
            for f in obj.fields:
                out.append(f"    pub {rs_ident(f.name)}: {rs_type(model, f.type)},")
            out.append("}")
    out += ["", 'extern "C" {']
    for func in model.funcs:
        params = ", ".join(f"{rs_ident(p.name)}: {rs_type(model, p.type)}" for p in func.params)
        out.append(f"    pub fn {func.name}({params}){rs_return(model, func.ret)};")
    out += ["}", ""]
    return "\n".join(out)


def gen_rust_test(model: Model) -> str:
    out = [
        f"// {BANNER}",
        f"// {COPYRIGHT}",
        f"// {GENERATED}",
        "//! Compares Rust FFI layout with the compiler-observed C ABI oracle.",
        "",
        "use mimhid_sys::*;",
        "use std::collections::BTreeMap;",
        "use std::mem::{offset_of, size_of};",
        "use std::process::Command;",
        "",
        "fn rust_layout() -> BTreeMap<String, i64> {",
        "    let mut map = BTreeMap::new();",
    ]
    for name, _, _ in all_constants(model):
        out.append(f'    map.insert("{name}".to_owned(), {name} as i64);')
    for struct in model.structs.values():
        out.append(f'    map.insert("{struct.name}.size".to_owned(), '
                   f"size_of::<{struct.name}>() as i64);")
        for f in struct.fields:
            out.append(f'    map.insert("{struct.name}.{f.name}".to_owned(), '
                       f"offset_of!({struct.name}, {rs_ident(f.name)}) as i64);")
    out += [
        "    map", "}", "",
        "#[test]",
        "fn layout_matches_the_c_compiler() {",
        '    let oracle = std::env::var("MIMHID_ABI_ORACLE")',
        '        .expect("MIMHID_ABI_ORACLE names the built layout_oracle program");',
        '    let output = Command::new(oracle).output().expect("the oracle runs");',
        "    assert!(output.status.success());",
        "    let mut expected = BTreeMap::new();",
        "    for line in String::from_utf8(output.stdout).expect(\"utf-8\").lines() {",
        '        let (key, value) = line.split_once(\'=\').expect("key=value");',
        '        expected.insert(key.to_owned(), value.parse::<i64>().expect("integer"));',
        "    }",
        "    assert_eq!(rust_layout(), expected);",
        "}", ""]
    return "\n".join(out)


