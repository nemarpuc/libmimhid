"""Generate the language bindings and the C layout oracle from the library's C header.

The same file serves libaoahid and libmimhid (the two copies differ only in the copyright line). Written
below for libmimhid; for libaoahid read "aoahid", "AOAHID" and "AoaHid" in place of "mimhid",
"MIMHID" and "MimHid". The header is the one source. This script reads it through clang's JSON AST and writes:

  tests/abi/layout_oracle.c                      prints sizes, offsets and constants as compiled
  bindings/python/mimhid/native.py               ctypes declarations
  bindings/python/tests/test_layout.py           compares them with the oracle
  bindings/csharp/MimHid/Native.cs               P/Invoke declarations
  bindings/csharp/MimHid.Tests/Program.cs        compares them with the oracle
  bindings/rust/mimhid-sys/src/lib.rs            FFI declarations
  bindings/rust/mimhid-sys/tests/layout.rs       compares them with the oracle

    python3 tools/bindings/generate.py           rewrite the files
    python3 tools/bindings/generate.py --check   fail when a file differs from the header

Only the exported functions are bound. The static inline initializers of mimhid.h are C code,
not part of the binary ABI; a binding fills every field itself, struct_size included.
"""

