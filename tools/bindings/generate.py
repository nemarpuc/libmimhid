def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="fail when a generated file differs from the header")
    args = parser.parse_args()
    try:
        model = load_model()
        check_names(model)
        stale = []
        for relative, generate in OUTPUTS.items():
            text = localize(generate(model))
            path = ROOT / localize(relative)
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != text:
                    stale.append(relative)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
        if stale:
            print(f"generated files differ from {HEADER_NAME} (run tools/bindings/generate.py): "
                  + ", ".join(stale), file=sys.stderr)
            return 1
        if args.check:
            print(f"bindings match {NAME}.h: {len(model.funcs)} functions, "
                  f"{len(model.structs)} structures, {len(all_constants(model))} constants")
    except GenerateError as error:
        print(f"generate: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
